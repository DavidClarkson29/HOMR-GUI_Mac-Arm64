def configure_gui_file_logging() -> Path:
    ensure_runtime_directories()
    log_path = cache_dir() / "homr-gui.log"
    resolved_log_path = log_path.resolve()
    if not any(
        isinstance(handler, RotatingFileHandler)
        and Path(handler.baseFilename).resolve() == resolved_log_path
        for handler in logger.handlers
    ):
        handler = RotatingFileHandler(
            log_path,
            maxBytes=1_000_000,
            backupCount=2,
            encoding="utf-8",
        )
        handler.setFormatter(
            logging.Formatter("%(asctime)s %(levelname)s %(threadName)s %(message)s")
        )
        logger.addHandler(handler)
    logger.setLevel(logging.INFO)
    logger.info("HOMR GUI logging started")
    return log_path


def image_content_id(image: QImage) -> str:
    """Return a stable fingerprint instead of relying on Qt's transient cache key."""
    normalized = image.convertToFormat(QImage.Format.Format_RGBA8888)
    pixels = normalized.bits().asstring(normalized.sizeInBytes())
    metadata = f"{normalized.width()}x{normalized.height()}".encode()
    return hashlib.sha256(metadata + pixels).hexdigest()


def convert_score_to_midi(img_path: str, use_accelerated_inference: bool) -> str:
    log_onnxruntime_status(use_accelerated_inference)
    download_weights(use_accelerated_inference)
    config = ProcessingConfig(
        enable_debug=False,
        enable_cache=False,
        write_staff_positions=False,
        read_staff_positions=False,
        selected_staff=-1,
        use_gpu_inference=use_accelerated_inference,
    )
    process_image(img_path, config, XmlGeneratorArguments(False, None, None))
    out_xml = os.path.splitext(img_path)[0] + ".musicxml"
    out_mid = os.path.splitext(img_path)[0] + ".mid"
    if not os.path.exists(out_xml):
        raise RuntimeError("AI 识别完成，但未能生成 XML 文件")
    score = converter.parse(out_xml)
    stabilize_measure_offsets(score)
    realize_midi_tremolos(score)
    realize_midi_arpeggios(score)
    score.write("midi", fp=out_mid)
    return out_mid


