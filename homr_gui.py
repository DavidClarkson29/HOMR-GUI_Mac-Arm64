class WorkerThread(QThread):
    finished = pyqtSignal(str)
    error = pyqtSignal(str)

    def __init__(self, img_path, use_accelerated_inference=True):
        super().__init__()
        self.img_path = img_path
        self.use_accelerated_inference = use_accelerated_inference

    def run(self):
        try:
            out_mid = convert_score_to_midi(
                self.img_path,
                self.use_accelerated_inference,
            )
            self.finished.emit(out_mid)

        except Exception as e:
            # 捕获并输出详细错误，方便排查
            logger.exception("Score recognition failed")
            self.error.emit(f"识别失败: {str(e)}")


class CaptureButton(QPushButton):
    """Treat a click as capture and a real pointer drag as MIDI export."""

    dragRequested = pyqtSignal()

    def __init__(self, parent=None):
        super().__init__(parent)
        self._press_position = None
        self._drag_started = False

    def mousePressEvent(self, event):
        if event.button() == Qt.MouseButton.LeftButton:
            self._press_position = event.position().toPoint()
            self._drag_started = False
        super().mousePressEvent(event)

    def mouseMoveEvent(self, event):
        if (
            self._press_position is not None
            and event.buttons() & Qt.MouseButton.LeftButton
            and (event.position().toPoint() - self._press_position).manhattanLength()
            >= QApplication.startDragDistance()
        ):
            self._drag_started = True
            self.setDown(False)
            self.dragRequested.emit()
            return
        super().mouseMoveEvent(event)

    def mouseReleaseEvent(self, event):
        self._press_position = None
        if self._drag_started:
            self._drag_started = False
            event.accept()
            return
        super().mouseReleaseEvent(event)


